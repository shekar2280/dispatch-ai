import { test, expect } from '../support/fixtures';
import { selectBookingDate } from '../support/booking';
import { openPersona } from '../support/persona';

test('cashier collects payment and books a linked report review through the dialogs @journey', async ({ actor, browser }) => {
  const clinician = await openPersona(browser, 'doctor', actor);
  let visit;
  try {
    visit = await clinician.actor.walkIn();
    actor.visits.add(visit.id);
    await clinician.actor.json(`/api/v1/appointments/${visit.id}/call`, 'POST');
    await clinician.actor.json(`/api/v1/appointments/${visit.id}/start-consultation`, 'POST');
    await clinician.actor.json(`/api/v1/appointments/${visit.id}/complete`, 'POST');
  } finally { await clinician.context.close(); }
  await actor.page.reload();
  await actor.page.getByRole('button', { name: /^Completed/ }).click();
  await actor.page.getByPlaceholder('Search name, phone, or token...').fill(visit!.patient_name);
  const patient = actor.page.getByRole('link', { name: visit!.patient_name, exact: true });
  await expect(patient).toBeVisible();
  const row = patient.locator('xpath=ancestor::div[contains(@class, "border-b")][1]');
  await row.getByRole('button', { name: /Due/ }).click();
  await expect(actor.page.getByRole('heading', { name: 'Create bill', exact: true })).toBeVisible();
  const modal = actor.page.getByRole('dialog', { name: 'Create bill', exact: true });
  await modal.getByLabel('Consultation fee', { exact: true }).fill('100');
  await expect(modal.getByLabel('Collect now', { exact: true })).toHaveCount(0);
  await modal.getByRole('button', { name: 'Add medicine or charge' }).click();
  await modal.getByLabel('Item name', { exact: true }).fill('Test medicine');
  await modal.getByLabel('Item price', { exact: true }).fill('75');
  await expect(modal.getByRole('button', { name: 'Paid by cash' })).toBeDisabled();
  await modal.getByRole('button', { name: 'Add item', exact: true }).click();
  await modal.getByLabel('Quantity for Test medicine').fill('2');
  await modal.getByRole('button', { name: 'Close new item' }).click();
  const receiptResponse = actor.page.waitForResponse(response => response.url().includes(`/${visit!.id}/collect-fee`) && response.request().method() === 'PATCH');
  await actor.page.getByRole('button', { name: 'Paid by cash', exact: true }).click();
  expect((await receiptResponse).status()).toBe(200);
  const receipts = await actor.json<{ method: string; amount: number }[]>(`/api/v1/clinic/${visit!.id}/payments`);
  expect(receipts).toHaveLength(1);
  expect(receipts[0].method.toLowerCase()).toBe('cash');
  expect(Number(receipts[0].amount)).toBe(250);
  await expect(modal).toBeHidden();
  await row.getByTitle('More options').click();
  await actor.page.getByRole('button', { name: 'Book report review', exact: true }).click();
  const report = actor.page.getByRole('dialog', { name: 'Book report review' });
  await expect(report.getByText('Select doctor', { exact: true })).toHaveCount(0);
  const slot = await actor.futureSlot();
  await selectBookingDate(actor.page, slot.date);
  await report.getByRole('radio', { name: slot.time, exact: true }).click();
  await expect(report.getByLabel('Patient name', { exact: true })).toHaveValue(visit!.patient_name);
  const bookingResponse = actor.page.waitForResponse(response => response.url().endsWith('/api/v1/appointments/book') && response.request().method() === 'POST');
  await report.getByRole('button', { name: 'Book appointment', exact: true }).click();
  const result = await bookingResponse;
  expect(result.status()).toBe(201);
  const review = await result.json();
  actor.visits.add(review.id);
  expect(review.patient_id).toBe(visit!.patient_id);
  expect(review.doctor_id).toBe(actor.doctorId);
  expect(review.previous_visit_id).toBe(visit!.id);
  expect((await actor.readVisit(review.id)).previous_visit_id).toBe(visit!.id);
});
